#!/bin/bash
set -e

# Espera a PostgreSQL (pg_isready no necesita contrasena)
while ! pg_isready -q -h "${MAIL_DB_HOST}" -p "${MAIL_DB_PORT:-5432}" -U "${MAIL_DB_USER}" -d "${MAIL_DB_NAME}"; do
  echo "Waiting for database to come up..."
  sleep 2
done

until dig +short letsencrypt.org > /dev/null; do
  echo "Waiting for DNS..."
  sleep 1
done

# Do not attempt to write to slave
if [[ ! -z ${REDIS_SLAVEOF_IP} ]]; then
  REDIS_CMDLINE="redis-cli -h ${REDIS_SLAVEOF_IP} -p ${REDIS_SLAVEOF_PORT} -a ${MAIL_REDIS_PASSWORD} --no-auth-warning"
else
  REDIS_CMDLINE="redis-cli -h ${MAIL_REDIS_HOST} -p 6379 -a ${MAIL_REDIS_PASSWORD} --no-auth-warning"
fi

until [[ $(${REDIS_CMDLINE} PING) == "PONG" ]]; do
  echo "Waiting for Redis..."
  sleep 2
done

${REDIS_CMDLINE} SET DOVECOT_REPL_HEALTH 1 > /dev/null

# Create missing directories
[[ ! -d /etc/dovecot/sql/ ]] && mkdir -p /etc/dovecot/sql/
[[ ! -d /etc/dovecot/auth/ ]] && mkdir -p /etc/dovecot/auth/
[[ ! -d /etc/dovecot/conf.d/ ]] && mkdir -p /etc/dovecot/conf.d/
[[ ! -d /etc/dovecot-auth/ ]] && mkdir -p /etc/dovecot-auth/
[[ ! -d /var/vmail/_garbage ]] && mkdir -p /var/vmail/_garbage
[[ ! -d /var/vmail/sieve ]] && mkdir -p /var/vmail/sieve
[[ ! -d /var/volatile ]] && mkdir -p /var/volatile

# Set Dovecot sql config parameters, escape " in db password
MAIL_DB_PASSWORD_ESCAPED=$(echo ${MAIL_DB_PASSWORD} | sed 's/"/\\"/g')
DOVECOT_PG_CONNECT="host=${MAIL_DB_HOST} port=${MAIL_DB_PORT:-5432} dbname=${MAIL_DB_NAME} user=${MAIL_DB_USER} password=${MAIL_DB_PASSWORD_ESCAPED}"

# Create quota dict for Dovecot: Dovecot writes bytes/messages into mail.quota_usage (upsert on username)
cat <<EOF > /etc/dovecot/sql/dovecot-dict-sql-quota.conf
# Autogenerated by Core Force Mail
connect = "${DOVECOT_PG_CONNECT}"
map {
  pattern = priv/quota/storage
  table = mail.quota_usage
  username_field = username
  value_field = bytes
}
map {
  pattern = priv/quota/messages
  table = mail.quota_usage
  username_field = username
  value_field = messages
}
EOF

# Create dict used for sieve pre and postfilters (read-only views over mail.sieve_filters)
cat <<EOF > /etc/dovecot/sql/dovecot-dict-sql-sieve_before.conf
# Autogenerated by Core Force Mail
connect = "${DOVECOT_PG_CONNECT}"
map {
  pattern = priv/sieve/name/\$script_name
  table = mail.v_sieve_before
  username_field = username
  value_field = id
  fields {
    script_name = \$script_name
  }
}
map {
  pattern = priv/sieve/data/\$id
  table = mail.v_sieve_before
  username_field = username
  value_field = script_data
  fields {
    id = \$id
  }
}
EOF

cat <<EOF > /etc/dovecot/sql/dovecot-dict-sql-sieve_after.conf
# Autogenerated by Core Force Mail
connect = "${DOVECOT_PG_CONNECT}"
map {
  pattern = priv/sieve/name/\$script_name
  table = mail.v_sieve_after
  username_field = username
  value_field = id
  fields {
    script_name = \$script_name
  }
}
map {
  pattern = priv/sieve/data/\$id
  table = mail.v_sieve_after
  username_field = username
  value_field = script_data
  fields {
    id = \$id
  }
}
EOF

# Respuesta automatica de cada buzon: la genera mail-directory y la lee la vista v_sieve_vacation,
# en su propia ranura (sieve_after3) para no mezclarse con los filtros escritos a mano.
cat <<EOF > /etc/dovecot/sql/dovecot-dict-sql-sieve_vacation.conf
# Autogenerated by Core Force Mail
connect = "${DOVECOT_PG_CONNECT}"
map {
  pattern = priv/sieve/name/\$script_name
  table = mail.v_sieve_vacation
  username_field = username
  value_field = id
  fields {
    script_name = \$script_name
  }
}
map {
  pattern = priv/sieve/data/\$id
  table = mail.v_sieve_vacation
  username_field = username
  value_field = script_data
  fields {
    id = \$id
  }
}
EOF

echo -n ${ACL_ANYONE} > /etc/dovecot/acl_anyone

if [[ "${SKIP_FTS}" =~ ^([yY][eE][sS]|[yY])+$ ]]; then
echo -e "\e[33mDetecting SKIP_FTS=y... not enabling Flatcurve (FTS) then...\e[0m"
echo -n 'quota acl zlib mail_crypt mail_crypt_acl mail_log notify listescape replication lazy_expunge' > /etc/dovecot/mail_plugins
echo -n 'quota imap_quota imap_acl acl zlib imap_zlib imap_sieve mail_crypt mail_crypt_acl notify listescape replication mail_log' > /etc/dovecot/mail_plugins_imap
echo -n 'quota sieve acl zlib mail_crypt mail_crypt_acl notify listescape replication' > /etc/dovecot/mail_plugins_lmtp
else
echo -e "\e[32mDetecting SKIP_FTS=n... enabling Flatcurve (FTS)\e[0m"
echo -n 'quota acl zlib mail_crypt mail_crypt_acl mail_log notify fts fts_flatcurve listescape replication lazy_expunge' > /etc/dovecot/mail_plugins
echo -n 'quota imap_quota imap_acl acl zlib imap_zlib imap_sieve mail_crypt mail_crypt_acl notify mail_log fts fts_flatcurve listescape replication' > /etc/dovecot/mail_plugins_imap
echo -n 'quota sieve acl zlib mail_crypt mail_crypt_acl fts fts_flatcurve notify listescape replication' > /etc/dovecot/mail_plugins_lmtp
fi
chmod 644 /etc/dovecot/mail_plugins /etc/dovecot/mail_plugins_imap /etc/dovecot/mail_plugins_lmtp /templates/quota.tpl

# %d/%n/%u/%s are Dovecot variables; MAILDIR_SUB is expanded here by the shell.
cat <<EOF > /etc/dovecot/sql/dovecot-dict-sql-userdb.conf
# Autogenerated by Core Force Mail
driver = pgsql
connect = "${DOVECOT_PG_CONNECT}"
user_query = SELECT mailbox_format || path_prefix || '%d/%n/${MAILDIR_SUB}:VOLATILEDIR=/var/volatile/%u:INDEX=/var/vmail_index/%u' AS mail, '%s' AS protocol, 5000 AS uid, 5000 AS gid, '*:bytes=' || quota_bytes AS quota_rule FROM mail.mailboxes WHERE username = '%u' AND active IN (1, 2)
iterate_query = SELECT username FROM mail.mailboxes WHERE active IN (1, 2)
EOF

# Render the Lua passdb outside the bind-mounted conf dir so the template in the repo is never rewritten
envsubst '${MAIL_AUTH_URL}' < /etc/dovecot/auth/passwd-verify.lua > /etc/dovecot-auth/passwd-verify.lua

# Migrate old sieve_after file
[[ -f /etc/dovecot/sieve_after ]] && mv /etc/dovecot/sieve_after /etc/dovecot/global_sieve_after
# Create global sieve scripts
cat /etc/dovecot/global_sieve_after > /var/vmail/sieve/global_sieve_after.sieve
cat /etc/dovecot/global_sieve_before > /var/vmail/sieve/global_sieve_before.sieve

# Check permissions of vmail/index/garbage directories.
# Do not do this every start-up, it may take a very long time. So we use a stat check here.
if [[ $(stat -c %U /var/vmail/) != "vmail" ]] ; then chown -R vmail:vmail /var/vmail ; fi
if [[ $(stat -c %U /var/vmail/_garbage) != "vmail" ]] ; then chown -R vmail:vmail /var/vmail/_garbage ; fi
if [[ $(stat -c %U /var/vmail_index) != "vmail" ]] ; then chown -R vmail:vmail /var/vmail_index ; fi

# Cleanup random user maildirs
rm -rf /var/vmail/platform.local/*

# create sni configuration
echo "" > /etc/dovecot/sni.conf
for cert_dir in /etc/ssl/mail/*/ ; do
  if [[ ! -f ${cert_dir}domains ]] || [[ ! -f ${cert_dir}cert.pem ]] || [[ ! -f ${cert_dir}key.pem ]]; then
    continue
  fi
  domains=($(cat ${cert_dir}domains))
  for domain in ${domains[@]}; do
    echo 'local_name '${domain}' {' >> /etc/dovecot/sni.conf;
    echo '  ssl_cert = <'${cert_dir}'cert.pem' >> /etc/dovecot/sni.conf;
    echo '  ssl_key = <'${cert_dir}'key.pem' >> /etc/dovecot/sni.conf;
    echo '}' >> /etc/dovecot/sni.conf;
  done
done

# Usuario maestro: "<buzon>*<maestro>@platform.local" inicia sesion como cualquier buzon de la
# celda. Lo usa el webmail (services/webmail), con WEBMAIL_MASTER_USER =
# ${DOVECOT_MASTER_USER}@platform.local y WEBMAIL_MASTER_PASSWORD = DOVECOT_MASTER_PASS, las dos
# del almacen de secretos. Sin ellas se genera uno aleatorio que nadie conoce.
# La contrasena se guarda con SHA512-CRYPT y la entrada solo vale desde
# DOVECOT_MASTER_ALLOWED_NETS (por defecto la red de los motores): una credencial maestra
# filtrada no abre buzones desde fuera de la celda.
RAND_USER=$(cat /dev/urandom | tr -dc 'a-z0-9' | fold -w 16 | head -n 1)
RAND_PASS=$(cat /dev/urandom | tr -dc 'a-z0-9' | fold -w 32 | head -n 1)

if [[ ! -z ${DOVECOT_MASTER_USER} ]] && [[ ! -z ${DOVECOT_MASTER_PASS} ]]; then
  if [[ ! ${DOVECOT_MASTER_USER} =~ ^[a-z0-9._-]+$ ]]; then
    echo "DOVECOT_MASTER_USER solo admite [a-z0-9._-]" >&2
    exit 1
  fi
  if [[ ${#DOVECOT_MASTER_PASS} -lt 32 ]]; then
    echo "DOVECOT_MASTER_PASS debe tener al menos 32 caracteres" >&2
    exit 1
  fi
  RAND_USER=${DOVECOT_MASTER_USER}
  RAND_PASS=${DOVECOT_MASTER_PASS}
fi
MASTER_NETS=${DOVECOT_MASTER_ALLOWED_NETS:-${IPV4_NETWORK:-172.22.1}.0/24}
if [[ ! ${MASTER_NETS} =~ ^[0-9a-fA-F.:/,]+$ ]]; then
  echo "DOVECOT_MASTER_ALLOWED_NETS debe ser una lista de CIDR separada por comas" >&2
  exit 1
fi
MASTER_HASH=$(printf '%s' "${RAND_PASS}" | openssl passwd -6 -stdin)
echo "${RAND_USER}@platform.local:{SHA512-CRYPT}${MASTER_HASH}::::::allow_nets=${MASTER_NETS}" > /etc/dovecot/dovecot-master.passwd
echo ${RAND_USER}@platform.local::5000:5000:::: > /etc/dovecot/dovecot-master.userdb

# Usuario maestro PROPIO de la migracion de buzones (mail-migration-runner, README.md, "Migracion de
# buzones"): opcional. Sin las dos variables no se anade nada; con ellas, una segunda entrada con su
# credencial y su propia red permitida (la red `mail-migration`, nunca la de los motores), de modo que
# la credencial del webmail y la del ejecutor no se pueden usar la una en lugar de la otra.
if [[ -n ${DOVECOT_MIGRATION_MASTER_USER} || -n ${DOVECOT_MIGRATION_MASTER_PASS} ]]; then
  if [[ -z ${DOVECOT_MIGRATION_MASTER_USER} || -z ${DOVECOT_MIGRATION_MASTER_PASS} ]]; then
    echo "DOVECOT_MIGRATION_MASTER_USER y DOVECOT_MIGRATION_MASTER_PASS van juntas" >&2
    exit 1
  fi
  if [[ ! ${DOVECOT_MIGRATION_MASTER_USER} =~ ^[a-z0-9._-]+$ ]]; then
    echo "DOVECOT_MIGRATION_MASTER_USER solo admite [a-z0-9._-]" >&2
    exit 1
  fi
  if [[ ${#DOVECOT_MIGRATION_MASTER_PASS} -lt 32 ]]; then
    echo "DOVECOT_MIGRATION_MASTER_PASS debe tener al menos 32 caracteres" >&2
    exit 1
  fi
  if [[ ${DOVECOT_MIGRATION_MASTER_USER} == "${RAND_USER}" ]]; then
    echo "DOVECOT_MIGRATION_MASTER_USER no puede ser el del webmail" >&2
    exit 1
  fi
  MIGRATION_NETS=${DOVECOT_MIGRATION_MASTER_ALLOWED_NETS:-${MAIL_MIGRATION_IPV4_NETWORK:-172.22.2}.0/24}
  if [[ ! ${MIGRATION_NETS} =~ ^[0-9a-fA-F.:/,]+$ ]]; then
    echo "DOVECOT_MIGRATION_MASTER_ALLOWED_NETS debe ser una lista de CIDR separada por comas" >&2
    exit 1
  fi
  MIGRATION_HASH=$(printf '%s' "${DOVECOT_MIGRATION_MASTER_PASS}" | openssl passwd -6 -stdin)
  echo "${DOVECOT_MIGRATION_MASTER_USER}@platform.local:{SHA512-CRYPT}${MIGRATION_HASH}::::::allow_nets=${MIGRATION_NETS}" >> /etc/dovecot/dovecot-master.passwd
  echo ${DOVECOT_MIGRATION_MASTER_USER}@platform.local::5000:5000:::: >> /etc/dovecot/dovecot-master.userdb
fi
chown root:dovecot /etc/dovecot/dovecot-master.passwd
chmod 640 /etc/dovecot/dovecot-master.passwd

# API HTTP de doveadm: mail-security vacia por ella la cache de autenticacion de un buzon y cierra
# sus sesiones cuando deja de poder entrar o cambia su credencial (README.md, "Revocacion en
# Dovecot"). Solo con DOVEADM_API_KEY, del almacen de secretos y la misma que recibe mail-security.
# TLS con el certificado del servidor de correo, sin puerto publicado y solo las ordenes de la
# revocacion: doveadm_allowed_commands vale tambien para el puerto 12345, asi que con replica se
# admite ademas dsync-server. El fichero va fuera del bind mount, como passwd-verify.lua.
DOVEADM_API_CONF=/etc/dovecot-auth/doveadm-api.conf
rm -f "${DOVEADM_API_CONF}"
if [[ -n ${DOVEADM_API_KEY} ]]; then
  # Largo y caracteres por separado: la regex de musl no admite repeticiones de mas de 255.
  if [[ ${#DOVEADM_API_KEY} -lt 32 || ${#DOVEADM_API_KEY} -gt 256 || ! ${DOVEADM_API_KEY} =~ ^[A-Za-z0-9_-]+$ ]]; then
    echo "DOVEADM_API_KEY debe tener de 32 a 256 caracteres de [A-Za-z0-9_-]" >&2
    exit 1
  fi
  DOVEADM_ALLOWED="kick,auth cache flush"
  if [[ -n ${MAIL_REPLICA_IP} && -n ${DOVEADM_REPLICA_PORT} ]]; then
    DOVEADM_ALLOWED="${DOVEADM_ALLOWED},dsync-server"
  fi
  (umask 077 && cat <<EOF > "${DOVEADM_API_CONF}"
# Autogenerated by Core Force Mail
doveadm_api_key = ${DOVEADM_API_KEY}
doveadm_allowed_commands = ${DOVEADM_ALLOWED}
service doveadm {
  inet_listener http {
    port = 8443
    ssl = yes
  }
}
EOF
  )
fi

if [[ -z ${MAILDIR_SUB} ]]; then
  MAILDIR_SUB_SHARED=
else
  MAILDIR_SUB_SHARED=/${MAILDIR_SUB}
fi
cat <<EOF > /etc/dovecot/shared_namespace.conf
# Autogenerated by Core Force Mail
namespace {
    type = shared
    separator = /
    prefix = Shared/%%u/
    location = maildir:%%h${MAILDIR_SUB_SHARED}:INDEX=~${MAILDIR_SUB_SHARED}/Shared/%%u
    subscriptions = no
    list = children
}
EOF

if [[ "${MASTER}" =~ ^([nN][oO]|[nN])+$ ]]; then
  # Toggling MASTER will result in a rebuild of containers, so the quota script will be recreated
  cat <<'EOF' > /usr/local/bin/quota_notify.py
#!/usr/bin/python3
import sys
sys.exit()
EOF
fi

# Set mail_replica for HA setups
if [[ -n ${MAIL_REPLICA_IP} && -n ${DOVEADM_REPLICA_PORT} ]]; then
  cat <<EOF > /etc/dovecot/mail_replica.conf
# Autogenerated by Core Force Mail
mail_replica = tcp:${MAIL_REPLICA_IP}:${DOVEADM_REPLICA_PORT}
EOF
fi

# Setting variables for indexer-worker inside fts.conf automatically according to .env settings
if [[ "${SKIP_FTS}" =~ ^([nN][oO]|[nN])+$ ]]; then
  echo -e "\e[94mConfiguring FTS Settings...\e[0m"
  echo -e "\e[94mSetting FTS Memory Limit (per process) to ${FTS_HEAP} MB\e[0m"
  sed -i "s/vsz_limit\s*=\s*[0-9]*\s*MB*/vsz_limit=${FTS_HEAP} MB/" /etc/dovecot/conf.d/fts.conf
  echo -e "\e[94mSetting FTS Process Limit to ${FTS_PROCS}\e[0m"
  sed -i "s/process_limit\s*=\s*[0-9]*/process_limit=${FTS_PROCS}/" /etc/dovecot/conf.d/fts.conf
fi

# 401 is user dovecot
if [[ ! -s /mail_crypt/ecprivkey.pem || ! -s /mail_crypt/ecpubkey.pem ]]; then
	openssl ecparam -name prime256v1 -genkey | openssl pkey -out /mail_crypt/ecprivkey.pem
	openssl pkey -in /mail_crypt/ecprivkey.pem -pubout -out /mail_crypt/ecpubkey.pem
	chown 401 /mail_crypt/ecprivkey.pem /mail_crypt/ecpubkey.pem
else
	chown 401 /mail_crypt/ecprivkey.pem /mail_crypt/ecpubkey.pem
fi

# Fix OpenSSL 3.X TLS1.0, 1.1 support (https://community.mailcow.email/d/4062-hi-all/20)
if grep -qE 'ssl_min_protocol\s*=\s*(TLSv1|TLSv1\.1)\s*$' /etc/dovecot/dovecot.conf /etc/dovecot/extra.conf; then
    sed -i '/\[openssl_init\]/a ssl_conf = ssl_configuration' /etc/ssl/openssl.cnf

    echo "[ssl_configuration]" >> /etc/ssl/openssl.cnf
    echo "system_default = tls_system_default" >> /etc/ssl/openssl.cnf
    echo "[tls_system_default]" >> /etc/ssl/openssl.cnf
    echo "MinProtocol = TLSv1" >> /etc/ssl/openssl.cnf
    echo "CipherString = DEFAULT@SECLEVEL=0" >> /etc/ssl/openssl.cnf
fi

# Compile sieve scripts
sievec /var/vmail/sieve/global_sieve_before.sieve
sievec /var/vmail/sieve/global_sieve_after.sieve
sievec /usr/lib/dovecot/sieve/report-spam.sieve
sievec /usr/lib/dovecot/sieve/report-ham.sieve

# Fix permissions
chown root:root /etc/dovecot/sql/*.conf
chown root:dovecot /etc/dovecot/sql/dovecot-dict-sql-sieve* /etc/dovecot/sql/dovecot-dict-sql-quota* /etc/dovecot-auth/passwd-verify.lua
chmod 640 /etc/dovecot/sql/*.conf /etc/dovecot-auth/passwd-verify.lua
chown -R vmail:vmail /var/vmail/sieve
chown -R vmail:vmail /var/volatile
chown -R vmail:vmail /var/vmail_index
adduser vmail tty
chmod g+rw /dev/console
chown root:tty /dev/console
chmod +x /usr/lib/dovecot/sieve/rspamd-pipe-ham \
  /usr/lib/dovecot/sieve/rspamd-pipe-spam \
  /usr/local/bin/trim_logs.sh \
  /usr/local/bin/sa-rules.sh \
  /usr/local/bin/clean_q_aged.sh \
  /usr/local/bin/maildir_gc.sh \
  /usr/local/sbin/stop-supervisor.sh \
  /usr/local/bin/quota_notify.py \
  /usr/local/bin/repl_health.sh \
  /usr/local/bin/optimize-fts.sh

# Prepare environment file for cronjobs
printenv | sed 's/^\(.*\)$/export \1/g' > /source_env.sh

# Clean old PID if any
[[ -f /var/run/dovecot/master.pid ]] && rm /var/run/dovecot/master.pid

# Envsubst maildir_gc
echo "$(envsubst < /usr/local/bin/maildir_gc.sh)" > /usr/local/bin/maildir_gc.sh

# Collect SA rules once now
/usr/local/bin/sa-rules.sh

# Run hooks
for file in /hooks/*; do
  if [ -x "${file}" ]; then
    echo "Running hook ${file}"
    "${file}"
  fi
done

# For some strange, unknown and stupid reason, Dovecot may run into a race condition, when this file is not touched before it is read by dovecot/auth
# May be related to something inside Docker, I seriously don't know
touch /etc/dovecot-auth/passwd-verify.lua

if [[ ! -z ${REDIS_SLAVEOF_IP} ]]; then
  cp /etc/syslog-ng/syslog-ng-redis_slave.conf /etc/syslog-ng/syslog-ng.conf
fi

exec "$@"
